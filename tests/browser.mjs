const server=createServer(async(req,res)=>{
  try {
    const pathname=new URL(req.url,'http://127.0.0.1').pathname;
    let file=({'/':'demo/index.html','/demo.bundle.js':'demo/demo.bundle.js'})[pathname];
    if(sourceMode&&pathname!=='/') {
      const candidate=resolve('.'+pathname);
      file=pathname==='/demo/demo.js'||sourceRoots.some(root=>candidate.startsWith(root))&&/\.(?:js|css)$/.test(candidate)?candidate:null;
    }
    if(!file){res.writeHead(404);res.end();return;}
    let content=await readFile(file,'utf8');
    if(sourceMode&&pathname==='/') content=content.replace('<script src="demo.bundle.js"></script>',`<script>window.process={env:{NODE_ENV:'production'}};</script><script type="importmap">${JSON.stringify(sourceImports)}</script><script type="module" src="/demo/demo.js"></script>`);
    // Browser-native ES modules need only an in-memory CSS string response;
    // source mode never bundles or writes extension/demo build artifacts.
    if(sourceMode&&file.endsWith('.css')) content=`export default ${JSON.stringify(content)};`;
    res.setHeader('Content-Type',/\.(?:js|css)$/.test(file)?'application/javascript':'text/html; charset=utf-8');
    res.end(content);
  } catch { res.writeHead(404);res.end(); }
});
